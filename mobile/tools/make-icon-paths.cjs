// Turns the website's icon sprite (public/icons/badges.svg, Phosphor Icons, MIT licence) into a list of paths the
// phone app can draw. Run from mobile/:  node tools/make-icon-paths.cjs
const fs = require('fs');
const path = require('path');

const sprite = fs.readFileSync(path.join(__dirname, '..', '..', 'public', 'icons', 'badges.svg'), 'utf8');
const icons = {};
for (const m of sprite.matchAll(/<symbol id="ph-([^"]+)"[^>]*>([\s\S]*?)<\/symbol>/g)) {
  const paths = [...m[2].matchAll(/<path d="([^"]+)"/g)].map((p) => p[1]);
  if (paths.length) icons[m[1]] = paths.join(' ');
}
const body = Object.entries(icons)
  .map(([name, d]) => `  '${name}': '${d}',`)
  .join('\n');
fs.writeFileSync(
  path.join(__dirname, '..', 'src', 'iconPaths.ts'),
  `// Generated by tools/make-icon-paths.cjs from the website's icon sprite. Phosphor Icons (MIT), 256 by 256 grid, filled.\n// Do not edit by hand.\nexport const ICON_PATHS: Record<string, string> = {\n${body}\n};\n`,
);
console.log(Object.keys(icons).length, 'icons');
