// Expo config plugin: lets the generated Android project sign a RELEASE build with our own upload key, which Google Play
// requires, without ever putting a key or a password in the repository.
//
//  - With no key set up, nothing changes: a release build is still signed with the debug key (fine for test APKs).
//  - With the four Gradle properties below set (put them in the Gradle user folder's gradle.properties, e.g.
//    D:\tools\gradle-home\gradle.properties, NEVER inside this project), release builds are signed with that key.
//  - Building an App Bundle (.aab) without the key stops with a clear message instead of making a bundle Google rejects.
//
//    TARABASA_UPLOAD_STORE_FILE=D:/secure/tarabasa-upload.keystore
//    TARABASA_UPLOAD_STORE_PASSWORD=...
//    TARABASA_UPLOAD_KEY_ALIAS=tarabasa-upload
//    TARABASA_UPLOAD_KEY_PASSWORD=...
//
// The android/ folder is regenerated by `expo prebuild`, so this runs every time instead of editing build.gradle by hand.
const { withAppBuildGradle } = require('expo/config-plugins');

const MARK = '// tarabasa-upload-signing';

const UPLOAD_CONFIG = `
        upload {
            ${MARK}
            if (project.hasProperty('TARABASA_UPLOAD_STORE_FILE')) {
                storeFile file(project.property('TARABASA_UPLOAD_STORE_FILE'))
                storePassword project.property('TARABASA_UPLOAD_STORE_PASSWORD')
                keyAlias project.property('TARABASA_UPLOAD_KEY_ALIAS')
                keyPassword project.property('TARABASA_UPLOAD_KEY_PASSWORD')
            }
        }`;

const BUNDLE_GUARD = `
${MARK}-guard
gradle.taskGraph.whenReady { graph ->
    if (graph.hasTask(':app:bundleRelease') && !project.hasProperty('TARABASA_UPLOAD_STORE_FILE')) {
        throw new GradleException('bundleRelease needs the upload key. Set TARABASA_UPLOAD_STORE_FILE, TARABASA_UPLOAD_STORE_PASSWORD, TARABASA_UPLOAD_KEY_ALIAS and TARABASA_UPLOAD_KEY_PASSWORD in the Gradle user folder gradle.properties. Google Play rejects a bundle signed with the debug key.')
    }
}
`;

module.exports = function withUploadSigning(config) {
  return withAppBuildGradle(config, (cfg) => {
    let src = cfg.modResults.contents;
    if (src.includes(MARK)) return cfg; // already applied

    // 1. A second signing config, "upload", next to "debug".
    if (!/signingConfigs\s*\{/.test(src)) throw new Error('with-upload-signing: no signingConfigs block found in app/build.gradle');
    src = src.replace(/signingConfigs\s*\{/, (m) => `${m}${UPLOAD_CONFIG}`);

    // 2. The release build type uses it when the key is set up, the debug key otherwise.
    const release = /(buildTypes\s*\{[\s\S]*?release\s*\{[\s\S]*?)signingConfig\s+signingConfigs\.debug/;
    if (!release.test(src)) throw new Error('with-upload-signing: could not find the release signingConfig line');
    src = src.replace(release, `$1signingConfig project.hasProperty('TARABASA_UPLOAD_STORE_FILE') ? signingConfigs.upload : signingConfigs.debug`);

    // 3. Refuse to make a bundle without the key.
    src += BUNDLE_GUARD;

    cfg.modResults.contents = src;
    return cfg;
  });
};
